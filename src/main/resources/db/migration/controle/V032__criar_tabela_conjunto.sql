CREATE TABLE conjunto (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    fonte_dado_id NUMBER(19,0) NOT NULL,
    competencia DATE NOT NULL,
    status_camada VARCHAR2(50) NOT NULL,
    cobertura_territorial MDSYS.SDO_GEOMETRY,
    PRIMARY KEY (id),
    CONSTRAINT fk_conj_fonte_dado FOREIGN KEY (fonte_dado_id) REFERENCES fonte_dado (id)
);

